// Regenerates scripts/data/characters.gen.ts from database/characters/*.json.
// Adding a character = drop a JSON file in database/characters and run `npm run build`.
import fs from "fs";
const ids = fs.readdirSync("database/characters").filter((f) => f.endsWith(".json")).map((f) => f.replace(".json", "")).sort();
let s = "/** AUTO-GENERATED by tools/gen-registry.mjs — do not edit. */\n";
for (const i of ids) s += `import ${i} from "../../database/characters/${i}.json";\n`;
s += `import type { CharacterDef } from "./types";\nexport const CHARACTER_DATA = [${ids.join(", ")}] as unknown as CharacterDef[];\n`;
fs.writeFileSync("scripts/data/characters.gen.ts", s);
console.log(`[gen-registry] ${ids.length} characters`);
