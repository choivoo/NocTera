// Embeds a manifest of RP/BP resources into the bundle so /noct:noct selftest can
// verify on-device that every referenced model/animation/texture/sound was packaged.
import fs from "fs";
import path from "path";
const RP = "resource_pack/NOCTERRA_RP";
const BP = "behavior_pack/NOCTERRA_BP";
const walk = (d, ext) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap((f) => (f.isDirectory() ? walk(path.join(d, f.name), ext) : f.name.endsWith(ext) ? [path.join(d, f.name)] : [])) : []);
const read = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
const geometries = walk(`${RP}/models`, ".json").flatMap((f) => (read(f)["minecraft:geometry"] ?? []).map((g) => g.description.identifier));
const animations = walk(`${RP}/animations`, ".json").flatMap((f) => Object.keys(read(f).animations ?? {}));
const textures = walk(`${RP}/textures`, ".png").map((f) => f.slice(RP.length + 1).replace(/\.png$/, ""));
const sounds = Object.keys(read(`${RP}/sounds/sound_definitions.json`).sound_definitions);
const items = walk(`${BP}/items`, ".json").map((f) => read(f)["minecraft:item"].description.identifier);
const entities = walk(`${BP}/entities`, ".json").map((f) => read(f)["minecraft:entity"].description.identifier);
const bpm = read(`${BP}/manifest.json`);
const api = Object.fromEntries(bpm.dependencies.filter((d) => d.module_name).map((d) => [d.module_name, d.version]));
const out = { packVersion: bpm.header.version.join("."), minEngine: bpm.header.min_engine_version.join("."), api, geometries, animations, textures, sounds, items, entities };
fs.writeFileSync("scripts/data/resources.gen.ts", `/** AUTO-GENERATED by tools/gen-resource-manifest.mjs — do not edit. */\nexport const RESOURCES = ${JSON.stringify(out)} as const;\n`);
console.log(`[gen-resource-manifest] ${geometries.length} geo, ${animations.length} anim, ${textures.length} tex, ${sounds.length} sounds, ${items.length} items, ${entities.length} entities`);
